#!/usr/bin/env python3
"""Generate website/data.js from manifest.yaml and the canonical skills.

Usage:
  python3 scripts/build_site_data.py          write website/data.js
  python3 scripts/build_site_data.py --check  exit 1 if website/data.js is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "website" / "data.js"
REPO = "cybercoretech/cybercore-agent-skills"
REF = "main"

STATUS_TEXT = {
    "verified": "Skill discovery confirmed against the agent's documentation.",
    "needs-setup": "Needs a one-time setup step before project skills load.",
    "unverified": "Experimental: project skill discovery is unverified.",
    "rules-only": "Rules only: this agent has no skills system.",
}


def split_skill(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    end = text.find("\n---\n", 4)
    meta = yaml.safe_load(text[4:end])
    return meta, text[end + 5:].strip() + "\n"


def title_from(body: str, fallback: str) -> str:
    for line in body.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def build() -> str:
    manifest = yaml.safe_load((ROOT / "manifest.yaml").read_text(encoding="utf-8"))
    groups = [
        {"id": gid, "title": g["title"], "default": bool(g.get("default")), "pack": g.get("pack")}
        for gid, g in manifest["groups"].items()
    ]
    skills = []
    for name, meta in manifest["skills"].items():
        front, body = split_skill(ROOT / "skills" / name / "SKILL.md")
        skills.append({
            "id": name,
            "name": title_from(body, name),
            "group": meta["group"],
            "category": meta["category"],
            "icon": meta["icon"],
            "desc": front["description"].strip(),
            "version": (front.get("metadata") or {}).get("version"),
            "full": body,
        })
    agents = []
    for aid, spec in manifest["agents"].items():
        agents.append({
            "id": aid,
            "name": spec["name"],
            "icon": spec.get("icon", ""),
            "badge": spec["badge"],
            "instructions": spec["instructions"],
            "rulesDir": spec["rules_dir"],
            "skillsDir": spec.get("skills_dir") or "",
            "script": spec["script"],
            "status": spec["status"],
            "statusText": STATUS_TEXT[spec["status"]],
            "notes": [n.replace("{project}", "/path/to/project") for n in spec.get("notes", [])],
        })
    data = {"repo": REPO, "ref": REF, "groups": groups, "skills": skills, "agents": agents}
    payload = json.dumps(data, ensure_ascii=False, indent=1)
    return ("// GENERATED by scripts/build_site_data.py from manifest.yaml and skills/.\n"
            "// Do not edit by hand.\n"
            f"window.CC_DATA = {payload};\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = build()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
    if args.check:
        if current != content:
            print("website/data.js is stale. Run: python3 scripts/build_site_data.py", file=sys.stderr)
            return 1
        print("website/data.js is up to date.")
        return 0
    if current != content:
        OUTPUT.write_text(content, encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    else:
        print("website/data.js is up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
