#!/usr/bin/env python3
"""Generate the Skills Explorer data files from manifest.yaml, skills/, and rules/.

Outputs:
  website/data.js  catalog loaded with the page: groups, agents, rules, and
                   skill metadata (no documentation bodies)
  website/docs.js  skill documentation, loaded on demand when a skill is
                   opened, searched, or copied

Usage:
  python3 scripts/build_site_data.py          write both files
  python3 scripts/build_site_data.py --check  exit 1 if either file is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DATA_OUT = ROOT / "website" / "data.js"
DOCS_OUT = ROOT / "website" / "docs.js"
REPO = "cybercoretech/cybercore-agent-skills"
REF = "main"
HEADER = "// GENERATED by scripts/build_site_data.py from manifest.yaml, skills/, and rules/.\n// Do not edit by hand.\n"

STATUS_TEXT = {
    "verified": "Skill discovery confirmed against the agent's documentation.",
    "needs-setup": "Needs a one-time setup step before skills load.",
    "unverified": "Experimental: skill discovery is unverified.",
    "rules-only": "Rules only: this agent has no skills system.",
}


def split_skill(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    end = text.find("\n---\n", 4)
    meta = yaml.safe_load(text[4:end])
    return meta, text[end + 5:].strip() + "\n"


def title_from(body: str, fallback: str) -> str:
    for line in body.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def skill_files(name: str) -> list[str]:
    base = ROOT / "skills" / name
    return sorted(str(p.relative_to(base)) for p in base.rglob("*") if p.is_file())


def build() -> tuple[str, str]:
    manifest = yaml.safe_load((ROOT / "manifest.yaml").read_text(encoding="utf-8"))
    groups = [
        {"id": gid, "title": g["title"], "default": bool(g.get("default")), "pack": g.get("pack")}
        for gid, g in manifest["groups"].items()
    ]
    skills, docs = [], {}
    for name, meta in manifest["skills"].items():
        front, body = split_skill(ROOT / "skills" / name / "SKILL.md")
        skills.append({
            "id": name,
            "name": title_from(body, name),
            "group": meta["group"],
            "category": meta["category"],
            "icon": meta["icon"],
            "desc": front["description"].strip(),
            "version": (front.get("metadata") or {}).get("version"),
            "files": skill_files(name),
        })
        docs[name] = body
    agents = []
    for aid, spec in manifest["agents"].items():
        agents.append({
            "id": aid,
            "name": spec["name"],
            "icon": spec.get("icon", ""),
            "badge": spec["badge"],
            "instructions": spec["instructions"],
            "rulesDir": spec["rules_dir"],
            "skillsDir": spec.get("skills_dir") or "",
            "script": spec["script"],
            "status": spec["status"],
            "statusText": STATUS_TEXT[spec["status"]],
            "notes": [n.replace("{project}", "~") for n in spec.get("notes", [])],
        })
    rules = []
    for rule in manifest["rules"]:
        text = (ROOT / "rules" / f"{rule}.md").read_text(encoding="utf-8").strip() + "\n"
        title = title_from(text, rule)
        body = text.split("\n", 1)[1].strip() + "\n" if text.startswith("# ") else text
        rules.append({"id": rule, "file": f"{rule}.md", "title": title, "body": body})

    data = {"repo": REPO, "ref": REF, "groups": groups, "skills": skills, "agents": agents, "rules": rules}
    data_js = HEADER + f"window.CC_DATA = {json.dumps(data, ensure_ascii=False, indent=1)};\n"
    docs_js = HEADER + f"window.CC_DOCS = {json.dumps(docs, ensure_ascii=False, indent=1)};\n"
    return data_js, docs_js


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in zip((DATA_OUT, DOCS_OUT), build()):
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {path.relative_to(ROOT)}")
    if args.check and stale:
        print(f"Stale: {', '.join(map(str, stale))}. Run: python3 scripts/build_site_data.py", file=sys.stderr)
        return 1
    if not stale:
        print("website/data.js and website/docs.js are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
